"""حاضنةُ نظام تعاون الوكلاء (ق٧٦): مرسِلٌ تسلسليّ صغير يُخرج المالكَ من دور الناقل بين الوكلاء.

هذا تنفيذٌ حاضن لا معماريةٌ دائمة: ديوان مختبرُه الأول لا حدودُه، ويُستخرج بعد إثباته إلى مستودعٍ مستقل. فما هو عامٌّ
(السجلّ، وآلة الحالات، ومحوِّلات الوكلاء، وبروتوكول المراجعة) لا يستورد شيئًا من ديوان مباشرةً إلا `core.ledger`
و`core.quoted` و`core.canonical`؛ وكلُّ ما يخصّ ديوان (المسائل، والوسوم، والمسارات، وجدول المراجعين، وقواعد التجميد)
يعيش خلف واجهة محوِّل المشروع في `team/projects/`. والحدُّ الأضعف معلَن في `docs/TEAM-BOUNDARY.md`: العمّالُ وكلاءُ CLI
على المضيف داخل نسخِ عملٍ منفصلة، ونسخةُ العمل ليست حدًّا أمنيًّا.
"""
from __future__ import annotations

import os
from pathlib import Path


def team_home() -> Path:
    """موطنُ الحالة خارج شجرة المستودع المحمية (السجلّ، وتثبيتات الطبيب، والمعايرة، والمخرجات الخام)."""
    return Path(os.environ.get("DIWAN_TEAM_HOME", str(Path.home() / ".diwan-team")))


def worktrees_root() -> Path:
    """مجلّدٌ واحد مُفهرَس لنسخ عمل التكليفات؛ `git worktree list` هو الفهرس الوحيد."""
    return Path(os.environ.get("DIWAN_TEAM_WORKTREES", str(Path.home() / "diwan-work" / "wt")))
